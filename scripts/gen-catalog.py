#!/usr/bin/env python3
"""Regenerates Sources/MurmurCore/ModelCatalog+Files.swift from the Hugging Face API.

Pins every URL to the repo's current commit sha so checksums cannot drift.
LFS files take their sha256 from the tree API (lfs.oid); small non-LFS files are
downloaded once and hashed locally. Python 3 stdlib only.
"""
import hashlib, json, os, sys, urllib.request

HF = "https://huggingface.co"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Sources", "MurmurCore", "ModelCatalog+Files.swift")

# id -> (repo, folder inside repo or "", file filter, relativePath prefix to strip)
MODELS = [
    ("parakeet", "FluidInference/parakeet-tdt-0.6b-v2-coreml", "",
     lambda p: p.split("/")[0] in ("Preprocessor.mlmodelc", "Encoder.mlmodelc", "Decoder.mlmodelc",
                                   "JointDecision.mlmodelc") or p in ("parakeet_vocab.json", "config.json")),
    ("whisper", "argmaxinc/whisperkit-coreml", "openai_whisper-large-v3-v20240930_turbo", lambda p: True),
    # WhisperKit 1.1.1 loads tokenizer.json (+ tokenizer_config.json, config.json) for the large-v3 variant from
    # openai/whisper-large-v3; with tokenizerFolder pointing at <model>/tokenizer it never touches the network.
    ("whisper", "openai/whisper-large-v3", "",
     lambda p: p in ("tokenizer.json", "tokenizer_config.json", "config.json"), "tokenizer/"),
    ("qwen", "unsloth/Qwen3-4B-Instruct-2507-GGUF", "", lambda p: p == "Qwen3-4B-Instruct-2507-Q4_K_M.gguf"),
]

def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "murmur-gen-catalog"})) as r:
        return r.read()

def sha_of(url):
    h = hashlib.sha256()
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "murmur-gen-catalog"})) as r:
        while chunk := r.read(1 << 20):
            h.update(chunk)
    return h.hexdigest()

def main():
    out = ["// GENERATED by scripts/gen-catalog.py. Do not edit by hand.", "import Foundation", "",
           "extension ModelCatalog {"]
    seen, groups = set(), {}
    for name, repo, folder, keep, *rest in MODELS:
        prefix = rest[0] if rest else ""
        rev = json.loads(get(f"{HF}/api/models/{repo}"))["sha"]
        tree_url = f"{HF}/api/models/{repo}/tree/{rev}" + (f"/{folder}" if folder else "") + "?recursive=true"
        entries = [e for e in json.loads(get(tree_url)) if e["type"] == "file"]
        rows = []
        for e in sorted(entries, key=lambda e: e["path"]):
            rel = e["path"][len(folder) + 1:] if folder else e["path"]
            if not keep(rel):
                continue
            rel = prefix + rel
            url = f"{HF}/{repo}/resolve/{rev}/{e['path']}"
            digest = e["lfs"]["oid"] if "lfs" in e else sha_of(url)
            size = e["lfs"]["size"] if "lfs" in e else e["size"]
            rows.append(f'        f("{rel}", "{repo}", "{rev}", "{e["path"]}", "{digest}", {size}),')
            print(f"{name}: {rel} {size}", file=sys.stderr)
        if name in seen:
            groups[name] += [f"        // {repo} @ {rev}", *rows]
        else:
            seen.add(name)
            groups[name] = [f"        // {repo} @ {rev}", *rows]
    for name, rows in groups.items():
        out += [f"    static let {name}Files: [ModelFile] = [", *rows, "    ]", ""]
    out += ["}", "",
            "private func f(_ rel: String, _ repo: String, _ rev: String, _ path: String, _ sha: String, _ bytes: Int64) -> ModelFile {",
            '    ModelFile(relativePath: rel, url: URL(string: "https://huggingface.co/\\(repo)/resolve/\\(rev)/\\(path)")!, sha256: sha, bytes: bytes)',
            "}", ""]
    with open(OUT, "w") as fh:
        fh.write("\n".join(out))

main()
